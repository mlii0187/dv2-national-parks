"""Bundle every chart spec and data file into js/offline-bundle.js.

Browsers block a page opened straight from disk (file://) from loading its JSON and CSV
files, so the charts would not draw. js/main.js loads this bundle only in that case and
reads the same files from it. On GitHub Pages the normal files in specs/ and data/ are used.

Run from the repository root after changing any spec or data file:
    python scripts/build_offline.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
files = {}
for folder in ("specs", "data"):
    for path in sorted((ROOT / folder).iterdir()):
        if path.is_file() and not path.name.startswith(("_", ".")):
            files[f"{folder}/{path.name}"] = path.read_text(encoding="utf-8")

out = ROOT / "js" / "offline-bundle.js"
out.write_text(
    "/* Generated by scripts/build_offline.py. Copies of specs/ and data/ for opening the page from disk. */\n"
    "window.DV2_FILES = " + json.dumps(files, ensure_ascii=False) + ";\n",
    encoding="utf-8",
)
print(f"Wrote {out.relative_to(ROOT)} with {len(files)} files ({out.stat().st_size // 1024} KB)")
